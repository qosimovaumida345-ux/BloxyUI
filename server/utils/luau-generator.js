function generateLuauCode({ componentType, icon, effect, animation, theme, customOptions }) {
  const { colors = {}, style = {} } = theme;
  const primaryColor = colors.primary || '#3498db';
  const secondaryColor = colors.secondary || '#2ecc71';
  const bgColor = colors.background || '#ffffff';
  const textColor = colors.text || '#333333';
  
  const cornerRadius = style.cornerRadius || 8;
  const borderWidth = style.borderWidth || 0;
  
  const hexToColor3 = (hex) => {
    hex = hex.replace('#', '');
    const r = parseInt(hex.substring(0, 2), 16) || 255;
    const g = parseInt(hex.substring(2, 4), 16) || 255;
    const b = parseInt(hex.substring(4, 6), 16) || 255;
    return `Color3.fromRGB(${r}, ${g}, ${b})`;
  };

  let code = `-- Generated by BloxyUI Generator\n`;
  code += `local TweenService = game:GetService("TweenService")\n\n`;

  code += `local function CreateComponent(parent)\n`;
  code += `    local container = Instance.new("Frame")\n`;
  code += `    container.Name = "BloxyUI_${componentType.name}"\n`;
  code += `    container.BackgroundColor3 = ${hexToColor3(bgColor)}\n`;
  code += `    container.Size = UDim2.new(0, 200, 0, 50)\n`;
  code += `    container.Position = UDim2.new(0.5, -100, 0.5, -25)\n`;
  code += `    container.Parent = parent\n\n`;

  if (cornerRadius > 0) {
    code += `    local corner = Instance.new("UICorner")\n`;
    code += `    corner.CornerRadius = UDim.new(0, ${cornerRadius})\n`;
    code += `    corner.Parent = container\n\n`;
  }
  
  if (borderWidth > 0) {
    code += `    local stroke = Instance.new("UIStroke")\n`;
    code += `    stroke.Thickness = ${borderWidth}\n`;
    code += `    stroke.Color = ${hexToColor3(primaryColor)}\n`;
    code += `    stroke.ApplyStrokeMode = Enum.ApplyStrokeMode.Border\n`;
    code += `    stroke.Parent = container\n\n`;
  }

  if (componentType && componentType.luauCode) {
    code += `    -- Component Code\n`;
    code += `    ${componentType.luauCode.replace(/\n/g, '\n    ')}\n\n`;
  } else {
    code += `    local label = Instance.new("TextLabel")\n`;
    code += `    label.Size = UDim2.new(1, 0, 1, 0)\n`;
    code += `    label.BackgroundTransparency = 1\n`;
    code += `    label.Text = "${componentType.name || 'Component'}"\n`;
    code += `    label.TextColor3 = ${hexToColor3(textColor)}\n`;
    code += `    label.Font = Enum.Font.GothamSemibold\n`;
    code += `    label.TextSize = 18\n`;
    code += `    label.Parent = container\n\n`;
  }

  if (icon) {
    code += `    -- Icon Code\n`;
    code += `    local iconImage = Instance.new("ImageLabel")\n`;
    code += `    iconImage.Name = "Icon"\n`;
    code += `    iconImage.Size = UDim2.new(0, 24, 0, 24)\n`;
    code += `    iconImage.Position = UDim2.new(0, 12, 0.5, -12)\n`;
    code += `    iconImage.BackgroundTransparency = 1\n`;
    code += `    iconImage.Image = "rbxassetid://${icon.assetId || '0'}"\n`;
    code += `    iconImage.ImageColor3 = ${hexToColor3(primaryColor)}\n`;
    code += `    iconImage.Parent = container\n\n`;
  }

  if (effect && effect.luauCode) {
    code += `    -- Effect Code\n`;
    code += `    ${effect.luauCode.replace(/\n/g, '\n    ')}\n\n`;
  }

  if (animation && animation.luauCode) {
    code += `    -- Animation Code\n`;
    code += `    ${animation.luauCode.replace(/\n/g, '\n    ')}\n\n`;
  }

  code += `    return container\n`;
  code += `end\n\n`;
  code += `return CreateComponent\n`;

  return code;
}

module.exports = { generateLuauCode };
